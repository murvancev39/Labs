#ifndef HASH_TABLE_CHAINED_H
#define HASH_TABLE_CHAINED_H

#include <stdio.h>
#include <stdlib.h>
#include "err_def.h"

/**
 * @file hash_table_chained.h
 * @brief Заголовочный файл для реализации хеш-таблицы методом цепочек.
 *
 * Содержит определения структур данных и прототипы функций для работы
 * с универсальной хеш-таблицей, разрешающей коллизии с помощью
 * односвязных списков.
 */

/**
 * @enum use_load_factor
 * @brief Перечисление для управления использованием коэффициента заполнения.
 */
typedef enum
{
    yea = 1, /**< Использовать автоматический рехешинг при переполнении. */
    no = 0,  /**< Не использовать коэффициент заполнения (отключить рехешинг). */
} use_load_factor;

/**
 * @struct Node
 * @brief Узел односвязного списка (цепочки коллизий).
 *
 * Описывает отдельный элемент, хранящийся в бакете хеш-таблицы.
 */
typedef struct Node
{
    void *key;           /**< Указатель на данные (ключ) произвольного типа. */
    struct Node *next;   /**< Указатель на следующий узел в цепочке коллизий. */
} node_t;

/**
 * @struct Hash_Table
 * @brief Структура управляющего контекста хеш-таблицы.
 *
 * Хранит все метаданные, массивы элементов и указатели на пользовательские
 * функции (хеширование и сравнение), необходимые для работы таблицы.
 */
typedef struct Hash_Table
{
    node_t **nodes_arr;       /**< Динамический массив указателей на списки (массив бакетов). */
    size_t size;              /**< Текущее максимальное количество бакетов в таблице. */
    unsigned *collision_arr;  /**< Массив для учета количества элементов (коллизий) в каждом бакете. */
    size_t count;             /**< Общее количество элементов, добавленных в таблицу. */
    float load_factor;        /**< Порог коэффициента заполнения. Если 0 — рехешинг отключен. */
    
    /**
     * @brief Указатель на функцию вычисления хеш-кода ключа.
     * @param key Указатель на объект ключа.
     * @return Вычисленный unsigned int хеш-код.
     */
    unsigned (*hash_f) (void *);
    
    /**
     * @brief Указатель на функцию сравнения двух ключей.
     * @param key1 Указатель на первый ключ.
     * @param key2 Указатель на второй ключ.
     * @return 0, если ключи эквивалентны; любое другое число, если не равны.
     */
    int (*cmp) (void *, void *);
} chained_hash_table_t;


/**
 * @brief Конструктор хеш-таблицы. Создает и инициализирует структуру таблицы.
 * * @param size Начальное количество бакетов в таблице.
 * @param load_factor Предельный коэффициент заполнения таблицы (count/size).
 * @param hash_f Указатель на функцию хеширования ключей.
 * @param cmp Указатель на функцию сравнения ключей (должна возвращать 0 при равенстве).
 * @return Указатель на созданную таблицу chained_hash_table_t*, или NULL при ошибке аллокации или неверных аргументах.
 */
chained_hash_table_t *chained_hash_table_ctr (size_t size, float load_factor,
                                unsigned (*hash_f) (void *), int (*cmp) (void *, void *));

/**
 * @brief Очищает содержимое таблицы, удаляя все элементы.
 * * Освобождает память под все узлы `node_t`, обнуляет счетчики коллизий и общий счетчик элементов.
 * Сам управляющий контекст таблицы и пустой массив бакетов остаются в памяти.
 * * @param table Указатель на очищаемую хеш-таблицу.
 */
void chained_hash_table_clean (chained_hash_table_t *table);

/**
 * @brief Деструктор хеш-таблицы. Полностью уничтожает таблицу.
 * * Освобождает память из-под всех узлов списков, служебных массивов бакетов и коллизий,
 * а также память самого контекста таблицы.
 * * @param table Указатель на уничтожаемую хеш-таблицу.
 */
void chained_hash_table_dtr (chained_hash_table_t *table);

/**
 * @brief Рекурсивно/итеративно освобождает память цепочки узлов списка.
 * * Внутренняя вспомогательная функция для глубокой очистки памяти списков бакета.
 * * @param node Указатель на голову освобождаемого списка нод.
 */
void nodes_dtr (node_t *node);

/**
 * @brief Добавляет новый ключ в хеш-таблицу.
 * * Вставляет элемент в начало списка соответствующего бакета. Если текущий load_factor
 * превышает заданный порог, автоматически запускается функция rehash().
 * * @param table Указатель на хеш-таблицу.
 * @param key Указатель на добавляемый ключ.
 * @return OK в случае успешного добавления, ALLOC_ERR при ошибке выделения памяти, ERR при некорректных аргументах.
 */
int chained_hash_table_add (chained_hash_table_t *table, void *key);

/**
 * @brief Внутренняя функция перехеширования (увеличения размеров таблицы).
 * * Выделяет новые массивы бакетов увеличенного в 2 раза размера, после чего
 * переносит туда все существующие ключи, пересчитывая индексы. Старая память списков освобождается.
 * * @param table Указатель на хеш-таблицу.
 * @param add_func Указатель на функцию добавления элемента (обычно передается chained_hash_table_add).
 * @return OK при успехе, ALLOC_ERR при нехватке памяти, ERR при критической ошибке аргументов.
 */
int rehash (chained_hash_table_t *table, int (*add_func) (chained_hash_table_t *, void *));

/**
 * @brief Удаляет элемент из таблицы по ключу.
 * * Находит узел, содержащий указанный ключ, исключает его из связного списка бакета
 * и освобождает память структуры `node_t`. Память самого пользовательского объекта `key` не освобождается.
 * * @param table Указатель на хеш-таблицу.
 * @param key Указатель на удаляемый ключ.
 * @return OK в случае успешного удаления, ERR если элемент не был найден или переданы неверные параметры.
 */
int chained_hash_table_delete (chained_hash_table_t *table, void *key);

/**
 * @brief Ищет элемент в хеш-таблице по ключу.
 * * @param table Указатель на хеш-таблицу.
 * @param key Указатель на искомый ключ.
 * @return OK, если элемент успешно найден; ERR, если элемент отсутствует или переданы невалидные указатели.
 */
int chained_hash_table_search (chained_hash_table_t *table, void *key);

#endif