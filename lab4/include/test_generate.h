#ifndef TEST_GENERATE_H
#define TEST_GENERATE_H

#include <stdio.h>
#include <stdlib.h>
#include "err_def.h"

/**
 * @file test_generate.h
 * @brief Модуль генерации тестовых данных для оценки качества хеш-функций.
 *
 * Содержит функции для создания динамических массивов псевдослучайных данных
 * различных типов (unsigned int, float, строки фиксированной длины). Все генераторы
 * используют фиксированное зерно (seed), что гарантирует воспроизводимость тестов.
 */

/**
 * @brief Генерирует массив случайных чисел типа unsigned int.
 *
 * @param[in] size Размер создаваемого массива.
 * @return Указатель на выделенную память с массивом чисел или NULL при ошибке.
 */
unsigned *unsigned_test_gen (size_t size);

/**
 * @brief Генерирует массив случайных строк (строк из латинских символов нижнего регистра).
 *
 * Каждая строка имеет случайную длину от 5 до 20 символов и завершается нуль-терминатором.
 * Память выделяется как под сам массив указателей, так и под каждую строку отдельно.
 *
 * @param[in] size Количество строк в массиве.
 * @return Указатель на массив строк (char**) или NULL при ошибке выделения памяти.
 */
char **string_test_gen (size_t size);

/**
 * @brief Генерирует массив случайных чисел типа float в диапазоне [-10.0, 10.0].
 *
 * @param[in] size Размер создаваемого массива.
 * @return Указатель на выделенную память с массивом вещественных чисел или NULL при ошибке.
 */
float *float_test_gen (size_t size);

#endif